export function applyLanguage(lang) {
  const dict = T[lang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) el.setAttribute('placeholder', dict[key]);
  });
  /* Attributes without a data-i18n-* hook (tab title, icon-only button labels,
     <noscript>) are synced here so they never stay English in a Persian UI. */
  document.title = dict.title;
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    if (dict[key]) el.setAttribute('aria-label', dict[key]);
  });
  const noscript = document.querySelector('noscript[data-i18n-noscript]');
  if (noscript) noscript.textContent = dict.noscript;
  document.body.setAttribute('dir', lang === 'fa' ? 'rtl' : 'ltr');
  document.documentElement.setAttribute('lang', lang);
}
